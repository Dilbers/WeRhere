def translate(text: str, language: str = "en") -> str:
    if language == "en":
        return text
    translated = TRANSLATIONS.get(language, {}).get(text)
    if translated is not None:
        return translated

    for prefix in ("Welcome back, ", "Welcome, ", "Username: ", "Update from your team: "):
        if text.startswith(prefix):
            translated_prefix = TRANSLATIONS.get(language, {}).get(prefix)
            if translated_prefix:
                return translated_prefix + text[len(prefix):]

    match = re.match(r"^(From|To) (.+)$", text)
    if match:
        label = TRANSLATIONS.get(language, {}).get(match.group(1), match.group(1))
        return f"{label} {match.group(2)}"

    match = re.fullmatch(r"(\d+) applications(?:  ·  (\d+) possible duplicate names)?", text)
    if match:
        count = int(match.group(1))
        noun = "başvuru" if language == "tr" else "aanvraag" if count == 1 else "aanvragen"
        result = f"{count} {noun}"
        if match.group(2):
            duplicate_noun = (
                "olası yinelenen ad" if language == "tr" else "mogelijke dubbele namen"
            )
            result += f"  ·  {match.group(2)} {duplicate_noun}"
        return result
    match = re.fullmatch(r"(\d+) actions?", text)
    if match:
        noun = "işlem" if language == "tr" else "actie"
        return f"{match.group(1)} {noun}"
    return text
